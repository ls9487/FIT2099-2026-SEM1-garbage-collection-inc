package game.items;

/**
 * This enum is used to indicate which abilities/capabilities an item has.
 * Differs from statistics in the sense that it shouldn't have an integer value associated with it.
 * Includes abilities like UNLOCKER (to open doors).
 *
 * @author echu0057
 */
public enum ItemAbilities
{
    UNLOCKER,
    STERILISER,
    CUTTER
}
